#!/usr/bin/env python3
"""Draws Encore's LCD segments (src/gui/meloetta/encore_art.c + .h).

Every sprite is a white shape with alpha, ARGB8888, tinted at draw time with
image_recolor, so a lit segment and its faint "ghost" are the same bitmap.
All the drawings are original (a note, a sour note, a rest, the singer).
Drawn at 4x and shrunk, for smooth edges.

    python3 tools/encore_art.py      (needs pillow)
"""
import math
import os
import sys

from PIL import Image, ImageDraw

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_C = os.path.join(REPO_ROOT, "src", "gui", "meloetta", "encore_art.c")
OUT_H = os.path.join(REPO_ROOT, "src", "gui", "meloetta", "encore_art.h")
PREVIEW = sys.argv[1] if len(sys.argv) > 1 else None
K = 4  # supersampling


def canvas(w, h):
    m = Image.new("L", (w * K, h * K), 0)
    return m, ImageDraw.Draw(m)


def s(*v):
    return [x * K for x in v]


def ellipse_rot(d, cx, cy, rx, ry, deg, fill=255):
    pts = []
    a = math.radians(deg)
    for i in range(64):
        t = 2 * math.pi * i / 64
        x, y = rx * math.cos(t), ry * math.sin(t)
        pts.append(((cx + x * math.cos(a) - y * math.sin(a)) * K, (cy + x * math.sin(a) + y * math.cos(a)) * K))
    d.polygon(pts, fill=fill)


def thick_path(d, pts, w, fill=255):
    p = [(x * K, y * K) for x, y in pts]
    d.line(p, fill=fill, width=int(w * K), joint="curve")
    r = w * K / 2
    for x, y in (p[0], p[-1]):
        d.ellipse((x - r, y - r, x + r, y + r), fill=fill)


def bezier(p0, p1, p2, n=24):
    return [((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
             (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]) for t in (i / n for i in range(n + 1))]


# Notes share one frame: 56 x 92, the head's centre at (20, 74) sits on a line.
NW, NH, HX, HY = 56, 92, 20, 74


def note():
    m, d = canvas(NW, NH)
    ellipse_rot(d, HX, HY, 15, 11, -22)
    thick_path(d, [(33, 70), (33, 10)], 5)
    thick_path(d, bezier((33, 10), (52, 24), (48, 48)), 5)
    return m


def sour():
    # a spiky burr of a head, and a bent stem
    m, d = canvas(NW, NH)
    pts = []
    for i in range(20):
        r = 17 if i % 2 == 0 else 9
        t = 2 * math.pi * i / 20 - math.pi / 2
        pts.append(((HX + r * math.cos(t)) * K, (HY + r * math.sin(t)) * K))
    d.polygon(pts, fill=255)
    d.ellipse(s(HX - 4, HY - 4, HX + 4, HY + 4), fill=0)  # a hole: reads as "wrong"
    thick_path(d, [(33, 64), (33, 10)], 5)
    thick_path(d, bezier((33, 10), (50, 14), (44, 40)), 5)  # the flag wilts
    return m


def rest():
    # a quarter rest, its waist on the line
    m, d = canvas(NW, NH)
    thick_path(d, [(18, 34), (32, 50), (20, 62), (34, 78)], 7)
    thick_path(d, bezier((34, 78), (12, 72), (24, 92 - 2)), 6)
    return m


# The singer: 100 x 120, centred on the line at (50, 60).
PW, PH = 100, 120


def singer(catch):
    m, d = canvas(PW, PH)
    hx, hy, hr = 44, 40, 25
    # a curl of hair, like a note's flag
    thick_path(d, bezier((38, 18), (34, 2), (52, 6)), 6)
    d.ellipse(s(hx - hr, hy - hr, hx + hr, hy + hr), fill=255)
    d.ellipse(s(50, 30, 58, 38), fill=0)  # eye
    mr = 10 if catch else 6
    d.ellipse(s(62 - mr, 50 - mr, 62 + mr, 50 + mr), fill=0)  # singing "O"
    # body
    d.polygon([(x * K, y * K) for x, y in ((30, 66), (58, 66), (64, 100), (24, 100))], fill=255)
    # the arm out front, raised when catching
    hand = (88, 44) if catch else (86, 72)
    thick_path(d, [(56, 74), hand], 7)
    d.ellipse(s(hand[0] - 7, hand[1] - 7, hand[0] + 7, hand[1] + 7), fill=255)
    # legs and feet
    for x in (30, 48):
        d.rectangle(s(x, 98, x + 7, 112), fill=255)
        d.ellipse(s(x - 1, 108, x + 13, 117), fill=255)
    return m


def miss_mark():
    m, d = canvas(34, 34)
    pts = []
    for i in range(16):
        r = 16 if i % 2 == 0 else 9
        t = 2 * math.pi * i / 16 - math.pi / 2
        pts.append(((17 + r * math.cos(t)) * K, (17 + r * math.sin(t)) * K))
    d.polygon(pts, fill=255)
    d.ellipse(s(13, 13, 21, 21), fill=0)
    return m


SPRITES = [
    ("encore_note", note()),
    ("encore_sour", sour()),
    ("encore_rest", rest()),
    ("encore_singer", singer(False)),
    ("encore_singer_catch", singer(True)),
    ("encore_miss", miss_mark()),
]


def shrink(m):
    return m.resize((m.width // K, m.height // K), Image.LANCZOS)


def main():
    c = ["// Generated by tools/encore_art.py -- do not edit by hand.", '#include "encore_art.h"', ""]
    h = ["// Generated by tools/encore_art.py -- do not edit by hand.", "#ifndef GUI_ENCORE_ART_H",
         "#define GUI_ENCORE_ART_H", "", '#include "lvgl/lvgl.h"', ""]
    for name, big in SPRITES:
        a = shrink(big)
        w, hgt = a.size
        data = []
        for v in a.getdata():
            data += [0xFF, 0xFF, 0xFF, v]
        c.append(f"static const uint8_t {name}_data[] = {{")
        for i in range(0, len(data), 16):
            c.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        c.append("};")
        c.append(f"const lv_image_dsc_t {name} = {{\n\t.header = {{\n\t\t.magic = LV_IMAGE_HEADER_MAGIC,\n"
                 f"\t\t.cf = LV_COLOR_FORMAT_ARGB8888,\n\t\t.w = {w},\n\t\t.h = {hgt},\n\t\t.stride = {w * 4},\n\t}},\n"
                 f"\t.data_size = sizeof({name}_data),\n\t.data = {name}_data,\n}};\n")
        h.append(f"extern const lv_image_dsc_t {name}; // {w}x{hgt}")
    h += ["", "#endif /* GUI_ENCORE_ART_H */", ""]
    open(OUT_C, "w").write("\n".join(c))
    open(OUT_H, "w").write("\n".join(h))
    if PREVIEW:
        sheet = Image.new("RGB", (480, 140), (24, 28, 26))
        x = 8
        for name, big in SPRITES:
            a = shrink(big)
            sheet.paste(Image.new("RGB", a.size, (140, 196, 106)), (x, 8), a)
            x += a.width + 10
        sheet.save(PREVIEW)


if __name__ == "__main__":
    main()
